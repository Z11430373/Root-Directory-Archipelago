import { readFile, writeFile, mkdir, readdir, stat } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import yaml from 'js-yaml';
import { build } from 'esbuild';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.dirname(here);
const slash = p => p.split(path.sep).join('/');
export async function compileData(sourceRoot = root) {
  const data = { yaml: {}, text: {} };
  async function walk(dir, extension, target) {
    for (const entry of (await readdir(path.join(sourceRoot, dir), { withFileTypes: true })).sort((a,b) => a.name.localeCompare(b.name, 'en'))) {
      const rel = slash(path.join(dir, entry.name));
      if (entry.isDirectory()) await walk(rel, extension, target);
      else if (!extension || rel.endsWith(extension)) {
        const text = await readFile(path.join(sourceRoot, rel), 'utf8');
        target[rel] = extension === '.yaml' ? yaml.load(text) : text;
      }
    }
  }
  for (const dir of ['chapters', 'quests', 'dialogue', 'branches', 'cards', 'world']) await walk(dir, '.yaml', data.yaml);
  for (const rel of ['demo/demo.yaml', 'demo/flow.yaml', 'demo/integrity.yaml', 'demo/import_rules.yaml', 'demo/dialogue/init_demo.yaml']) {
    data.yaml[rel] = yaml.load(await readFile(path.join(sourceRoot, rel), 'utf8'));
  }
  await walk('text', null, data.text);
  let refs = 0;
  async function checkRefs(value, where) {
    if (!value || typeof value !== 'object') return;
    for (const [key, child] of Object.entries(value)) {
      const at = `${where}.${key}`;
      if (key === 'content_ref' || key === 'text_ref') {
        if (typeof child !== 'string' || path.isAbsolute(child) || child.split(/[\\/]/).includes('..')) throw new Error(`Unsafe reference: ${at}`);
        const abs = path.join(sourceRoot, child);
        if (!(await stat(abs).catch(() => null))?.isFile()) throw new Error(`Missing reference: ${at} -> ${child}`);
        if (!Object.hasOwn(data.text, child)) data.text[child] = await readFile(abs, 'utf8');
        refs++;
      }
      await checkRefs(child, at);
    }
  }
  for (const [key, doc] of Object.entries(data.yaml)) await checkRefs(doc, key);
  const b0 = data.yaml['branches/B0.yaml'];
  const originals = new Set();
  function gather(value) {
    if (!value || typeof value !== 'object') return;
    for (const [k,v] of Object.entries(value)) {
      if (k === 'say' && typeof v === 'string') originals.add(v);
      gather(v);
    }
  }
  gather(b0);
  for (const rule of data.yaml['demo/flow.yaml'].rules) {
    for (const action of rule.do || []) {
      if (action.print?.startsWith('[init') && !originals.has(action.print)) throw new Error(`B0 fixed text mismatch: ${rule.id}`);
    }
  }
  const json = JSON.stringify(data).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
  const bytes = Buffer.byteLength(json);
  if (bytes >= 1_500_000) throw new Error(`Compiled data exceeds 1.5 MB: ${bytes}`);
  return { data, json, bytes, refs };
}

export async function main() {
  const result = await compileData();
  await mkdir(path.join(here, 'src'), { recursive: true });
  await writeFile(path.join(here, 'src/data.js'), `// Generated by build.mjs; edit source pack, not this file.\nexport const DATA = ${result.json};\n`);
  console.log(`Data: ${result.bytes} bytes; ${result.refs} content_ref/text_ref checked; B0 text matched.`);
  if (process.argv.includes('--data-only')) return;
  const entry = path.join(here, 'src/main.js');
  const hasEntry = !!await stat(entry).catch(() => null);
  const js = hasEntry ? (await build({ entryPoints: [entry], bundle: true, write: false, format: 'iife', target: 'es2020', minify: true, legalComments: 'inline' })).outputFiles[0].text : '"use strict";';
  if (/<\/script/i.test(js)) throw new Error('Bundle contains unsafe closing script tag.');
  const css = await readFile(path.join(here, 'src/ui/theme.css'), 'utf8').catch(() => 'html{color-scheme:dark;background:#101716;color:#e8efec}');
  const hash = text => createHash('sha256').update(text).digest('base64');
  const csp = `default-src 'none'; script-src 'sha256-${hash(js)}'; style-src 'sha256-${hash(css)}'; img-src data:; connect-src 'none'; base-uri 'none'; form-action 'none'; object-src 'none'`;
  const html = `<!doctype html>\n<html lang="zh-Hant"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1, interactive-widget=resizes-content"><meta http-equiv="Content-Security-Policy" content="${csp}"><meta name="color-scheme" content="dark light"><title>根目錄群島 · 第一夜</title><style>${css}</style></head><body><div id="app"></div><script>${js}</script></body></html>\n`;
  await mkdir(path.join(here, 'dist'), { recursive: true });
  await writeFile(path.join(here, 'dist/index.html'), html);
  console.log(`Built dist/index.html: ${Buffer.byteLength(html)} bytes (offline, CSP SHA-256).`);
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
